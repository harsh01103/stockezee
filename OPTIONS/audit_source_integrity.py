import argparse
import sys
import json
import time
import asyncio
from pathlib import Path
from datetime import datetime
import polars as pl
from loguru import logger
from dotenv import load_dotenv

from market.recorder import MarketRecorder
from auth.auth_manager import AuthManager

async def run_live_observation(duration_sec=120):
    auth_manager = AuthManager()
    if not auth_manager.is_token_valid():
        logger.error("No valid Upstox token. Cannot run live observation.")
        return 0, 0, 0, 0.0, 0.0
        
    recorder = MarketRecorder(auth_manager, dry_run=False)
    
    # Run the recorder in background for duration_sec
    task = asyncio.create_task(recorder.start())
    
    logger.info(f"Running live observation for {duration_sec} seconds...")
    await asyncio.sleep(duration_sec)
    
    # Shut down cleanly
    recorder.is_running = False
    recorder.provider.close()
    recorder.heartbeat.stop()
    await recorder.storage.flush()
    await recorder.nse_client.close()
    
    # Wait for task to finish
    try:
        await asyncio.wait_for(task, timeout=10.0)
    except asyncio.TimeoutError:
        pass
    except Exception as e:
        logger.error(f"Recorder exited with error: {e}")
        
    # Analyze the latest raw file generated by this session
    # The session_id is recorder.session_id, but the files are in data/raw/YYYY-MM-DD/
    now_str = datetime.now().strftime("%Y-%m-%d")
    base_dir = Path(f"data/raw/{now_str}")
    
    df = pl.DataFrame()
    if base_dir.exists():
        files = list(base_dir.glob("*.parquet"))
        if files:
            # Load the files generated recently (last few minutes)
            recent_files = [f for f in files if (time.time() - f.stat().st_mtime) < (duration_sec + 60)]
            if recent_files:
                dfs = [pl.read_parquet(f) for f in recent_files]
                df = pl.concat(dfs, how="vertical_relaxed")
                
    rows_written = df.height
    ltp_std = 0.0
    oi_std = 0.0
    instrument_count = 0
    real_frames = recorder.validator.messages_received
    mock_frames = 0
    
    if not df.is_empty():
        ltp_std = df["ltp"].std() if "ltp" in df.columns else 0.0
        oi_std = df["oi"].std() if "oi" in df.columns else 0.0
        
        # Handle nulls
        ltp_std = ltp_std if ltp_std is not None else 0.0
        oi_std = oi_std if oi_std is not None else 0.0
        
        
        if all(c in df.columns for c in ["underlying", "expiry", "strike", "option_type"]):
            # Group by these to find unique instruments
            instrument_count = df.select(["underlying", "expiry", "strike", "option_type"]).unique().height
        else:
            instrument_count = 0
        
        # Count mock writes if any (should be 0 because we reject them)
        if "source_type" in df.columns:
            mock_frames = df.filter(pl.col("source_type") == "MOCK").height
            
    return real_frames, mock_frames, rows_written, instrument_count, ltp_std, oi_std

def main():
    load_dotenv(override=True)
    parser = argparse.ArgumentParser()
    args = parser.parse_args()
    
    try:
        real_frames, mock_frames, rows_written, inst_count, ltp_std, oi_std = asyncio.run(run_live_observation(120))
    except Exception as e:
        logger.error(f"Failed to run observation: {e}")
        real_frames, mock_frames, rows_written, inst_count, ltp_std, oi_std = 0, 0, 0, 0, 0.0, 0.0
        
    movement_score = 1.0 if ltp_std > 0 else 0.0
    
    total_frames = real_frames + mock_frames
    real_source_ratio = real_frames / total_frames if total_frames > 0 else 0.0
    
    # We must explicitly reject if mock frames exist or ltp_std == 0 or rows_written < 1000
    pass1 = (mock_frames == 0)
    pass2 = (ltp_std > 0)
    pass3 = (rows_written >= 1000)
    
    passed = pass1 and pass2 and pass3 and (real_source_ratio == 1.0) and (movement_score > 0.60)
    
    root_cause = "NONE"
    if not passed:
        if mock_frames > 0:
            root_cause = "Mock frames were injected and written to parquet."
        elif rows_written < 1000:
            root_cause = "Insufficient rows written (websocket disconnected or no live market data)."
        elif ltp_std == 0:
            root_cause = "No variance in LTP. Market might be closed or mock data is fully flat."
    
    grade = "PASS" if passed else "FAIL"
    
    report = {
        "grade": grade,
        "real_source_ratio": real_source_ratio,
        "rows_written": rows_written,
        "movement_score": movement_score,
        "root_cause": root_cause
    }
    
    Path("reports").mkdir(exist_ok=True)
    with open("reports/phase1_source_integrity.json", "w") as f:
        json.dump(report, f, indent=2)
        
    print("\nFINAL OUTPUT")
    print(f"Grade: {report['grade']}")
    print(f"Real Source Ratio: {report['real_source_ratio']:.2f}")
    print(f"Rows Written: {report['rows_written']}")
    print(f"Movement Score: {report['movement_score']:.2f}")
    print(f"Root Cause: {report['root_cause']}")
    
    if passed:
        print("\nPASS")
    else:
        print("\nFAIL")

if __name__ == "__main__":
    main()
